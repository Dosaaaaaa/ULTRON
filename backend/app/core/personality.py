"""Personality engine.

The personality is a versioned text file (shared/prompts/ultron.v{N}.md). A version may also ship
`ultron.v{N}.local.md`: the SAME rules rendered for the small local model, which measurably needs
longer, more explicit wording and worked examples than the cloud model does (and the cloud's token
limit is what makes the shorter default worth having). Everything else is identical for every
provider. This module only loads the text and appends a generated runtime-context block that tells
the model, truthfully, which engine it is and what it can access. It contains no routing,
permission or reasoning logic.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from app.models.router import PromptContext


@dataclass(frozen=True)
class MemoryPrompt:
    """Long-term memory as one engine's prompt sees it (built per engine, see memory/context)."""

    enabled: bool
    block: str | None = None  # retrieved notes, already filtered for this engine's privacy tier
    remember_note: str | None = None  # outcome of a "remember that ..." command this turn
    project_line: str | None = None


@dataclass(frozen=True)
class WebPrompt:
    """Web search as one prompt sees it: whether it exists this turn, and what it returned."""

    enabled: bool = False
    block: str | None = None
    note: str | None = None  # why there is no result block ("skipped: local-only", "failed", ...)


@dataclass(frozen=True)
class Personality:
    version: int
    text: str
    sha256: str
    local_text: str | None = None  # rendering for the small local model, if the version has one
    local_sha256: str | None = None

    def text_for(self, tier: str) -> str:
        return self.local_text if tier == "local" and self.local_text else self.text


def load_personality(prompts_dir: Path, version: int) -> Personality:
    path = prompts_dir / f"ultron.v{version}.md"
    if not path.is_file():
        raise FileNotFoundError(f"personality v{version} not found at {path}")
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        raise ValueError(f"personality file {path} is empty")
    local_path = prompts_dir / f"ultron.v{version}.local.md"
    local_text = local_sha = None
    if local_path.is_file():
        local_text = local_path.read_text(encoding="utf-8").strip()
        if not local_text:
            raise ValueError(f"personality file {local_path} is empty")
        local_sha = hashlib.sha256(local_text.encode()).hexdigest()
    return Personality(
        version, text, hashlib.sha256(text.encode()).hexdigest(), local_text, local_sha
    )


_CAPABILITIES = (
    "- Capabilities in this build: text conversation only. You have NO tools, NO web "
    "access, NO access to files, applications or devices, and NO memory beyond the "
    "messages in this conversation. Never imply otherwise."
)
_CAPABILITIES_MEMORY = (
    "- Capabilities in this build: text conversation and long-term memory notes. You have NO "
    "tools, NO web access and NO access to files, applications or devices. Your only memory "
    "beyond this conversation is the 'Long-term memory' block below, when one is present. You "
    "cannot save, change or delete notes yourself: the operator does that (saying 'remember "
    "that ...' or using the memory controls). Never claim to remember or to have saved "
    "something unless it is in that block or the runtime context says it was saved."
)


_WEB_ON = (
    "- Web search: results retrieved just now are in the 'Web search results' block below. You "
    "cannot browse on your own; use only what the block contains and name the source."
)
_WEB_NONE = (
    "- Web search exists in this build but returned nothing for this message, so for this reply "
    "you have NO web access: do not claim to have looked anything up."
)


class PersonalityEngine:
    def __init__(self, personality: Personality) -> None:
        self.personality = personality

    def system_prompt(
        self,
        ctx: PromptContext,
        now: datetime | None = None,
        memory: MemoryPrompt | None = None,
        web: WebPrompt | None = None,
        working: str | None = None,
        action_note: str | None = None,
    ) -> str:
        now = now or datetime.now().astimezone()
        memory = memory or MemoryPrompt(enabled=False)
        web = web or WebPrompt()
        capabilities = _CAPABILITIES_MEMORY if memory.enabled else _CAPABILITIES
        if web.enabled:  # do not say "NO web access" and offer search results in the same prompt
            capabilities = capabilities.replace(
                "NO web access", "NO ability to browse the web yourself"
            )
        lines = [
            "# Runtime context (generated by the system; authoritative)",
            f"- Current date and time: {now.isoformat(timespec='minutes')}",
            f"- Answering engine: {ctx.tier} model '{ctx.model}' via {ctx.provider}",
            capabilities,
        ]
        if web.enabled:
            lines.append(_WEB_ON if web.block else _WEB_NONE)
        if memory.project_line:
            lines.append(f"- {memory.project_line}")
        if memory.remember_note:
            lines.append(
                "- The operator just asked you to remember something. Outcome: "
                + memory.remember_note
            )
        if action_note:
            lines.append("- Action requested this turn: " + action_note)
        if ctx.voice:
            lines.append(
                "- This reply will be SPOKEN ALOUD by a speech synthesiser. Use plain sentences "
                "only: no markdown, lists, symbols, code or URLs. Keep it to about three "
                "sentences unless the operator asked for more. Write numbers as they are spoken."
            )
        if ctx.local_only:
            lines.append("- This request is being processed entirely on the operator's own device.")
        if ctx.tier == "local":
            lines.append(
                "- You are a small local model with limited capability. When a question exceeds "
                "it, say so plainly. Never imply you match larger cloud models."
            )
        if ctx.degraded:
            lines.append(
                "- A more capable engine was preferred for this request but is not answering "
                "it. Be explicit about your uncertainty and recommend verification for anything "
                "consequential."
            )
        prompt = f"{self.personality.text_for(ctx.tier)}\n\n" + "\n".join(lines)
        for block in (memory.block, web.block, working):
            if block:
                prompt += f"\n\n{block.rstrip()}"
        return prompt
